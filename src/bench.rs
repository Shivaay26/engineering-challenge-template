//! `--benchmark-latency`: empirical latency experiments (Extension 4).
//!
//! Prints Markdown tables to **stdout** so the output can be pasted into
//! `LATENCY_DISCOVERIES.md`. This is the only mode where stdout is not SBE
//! bytes; progress and errors still go to stderr.
//!
//! Four experiments, each bounded so the whole suite finishes in a couple of
//! minutes:
//!
//! * **A** — connection-racing variance across 12 sockets.
//! * **B** — tuned vs default TCP sockets, one-way wire-to-process latency.
//! * **C** — shard density sweep (25 / 100 / 250 / 500 symbols per socket).
//! * **D** — parser and runtime overhead on representative payloads.

use std::{
    collections::HashSet,
    time::{Duration, Instant},
};

use chrono::Utc;
use futures_util::{SinkExt, StreamExt};
use tokio::time;
use tokio_tungstenite::tungstenite::Message;

use crate::{
    codec::{NormalizedEvent, VenueCodec, parse_scaled_1e6},
    net::{
        NetConfig,
        tuned_ws::{self, WsSocket, percentile},
    },
};

/// Sockets raced for Experiment A.
const RACE_SOCKETS: usize = 12;
/// Probes per socket for Experiment A.
const RACE_PROBES: usize = 30;
/// How long a feed may take to deliver all initial snapshots.
const WARMUP_LIMIT: Duration = Duration::from_secs(20);
/// Length of the delta-sampling window per configuration.
const SAMPLE_WINDOW: Duration = Duration::from_secs(12);

/// Runs every experiment and prints the combined Markdown report.
pub async fn run(client: &reqwest::Client, codec: &dyn VenueCodec) -> anyhow::Result<()> {
    println!("# Latency experiments");
    println!();
    println!("Live Polymarket, generated by `--benchmark-latency`.");
    println!();

    let symbols = discover_symbols(client, codec).await;
    eprintln!("benchmark: discovered {} symbol(s)", symbols.len());

    experiment_a(codec).await?;
    experiment_b(codec, &symbols).await?;
    experiment_c(codec, &symbols).await?;
    experiment_d(codec)?;

    Ok(())
}

/// Discovery is retried: the benchmark is useless without symbols, and this
/// network resets a large fraction of new TLS handshakes.
async fn discover_symbols(client: &reqwest::Client, codec: &dyn VenueCodec) -> Vec<String> {
    const ATTEMPTS: u32 = 8;

    for attempt in 1..=ATTEMPTS {
        match codec.fetch_active_symbols(client, Some(600)).await {
            Ok(symbols) if !symbols.is_empty() => return symbols,
            Ok(_) => eprintln!("benchmark: discovery returned no symbols ({attempt}/{ATTEMPTS})"),
            Err(error) => {
                eprintln!("benchmark: discovery failed ({attempt}/{ATTEMPTS}): {error:#}")
            }
        }
        time::sleep(Duration::from_secs(2)).await;
    }

    Vec::new()
}

/// A: how much RTT spread is there across many parallel sockets?
async fn experiment_a(codec: &dyn VenueCodec) -> anyhow::Result<()> {
    eprintln!("benchmark A: {RACE_SOCKETS} sockets x {RACE_PROBES} probes");

    let config = NetConfig {
        race_candidates: 1,
        ..NetConfig::default()
    };

    let probes = (0..RACE_SOCKETS).map(|_| async {
        let (mut socket, _) = tuned_ws::connect(codec, codec.ws_url(), &config).await?;
        let rtts = tuned_ws::probe_rtts(&mut socket, RACE_PROBES).await?;
        Ok::<_, anyhow::Error>(rtts)
    });

    let results = futures_util::future::join_all(probes).await;
    let mut samples: Vec<(Duration, Duration)> = Vec::new();
    for result in results {
        match result {
            Ok(mut rtts) => {
                rtts.sort_unstable();
                samples.push((percentile(&rtts, 50, 100), percentile(&rtts, 99, 100)));
            }
            Err(error) => eprintln!("benchmark A: candidate failed: {error:#}"),
        }
    }

    if samples.is_empty() {
        println!("## Experiment A — connection racing: no socket succeeded\n");
        return Ok(());
    }

    let mut p50s: Vec<Duration> = samples.iter().map(|(p50, _)| *p50).collect();
    let mut p99s: Vec<Duration> = samples.iter().map(|(_, p99)| *p99).collect();
    p50s.sort_unstable();
    p99s.sort_unstable();

    println!("## Experiment A — connection racing variance");
    println!();
    println!(
        "{} sockets, {} PING probes each.",
        samples.len(),
        RACE_PROBES
    );
    println!();
    println!("| Metric | min | median | max | spread |");
    println!("| --- | --- | --- | --- | --- |");
    println!(
        "| socket p50 | {} | {} | {} | {} |",
        ms(p50s[0]),
        ms(p50s[p50s.len() / 2]),
        ms(p50s[p50s.len() - 1]),
        ms(p50s[p50s.len() - 1].saturating_sub(p50s[0]))
    );
    println!(
        "| socket p99 | {} | {} | {} | {} |",
        ms(p99s[0]),
        ms(p99s[p99s.len() / 2]),
        ms(p99s[p99s.len() - 1]),
        ms(p99s[p99s.len() - 1].saturating_sub(p99s[0]))
    );
    println!();
    println!(
        "A spread of {} between the best and worst p50 is the Edge Lottery: \
         the same code, the same host, different Cloudflare workers.",
        ms(p50s[p50s.len() - 1].saturating_sub(p50s[0]))
    );
    println!();

    Ok(())
}

/// B: does TCP tuning beat the default socket options?
async fn experiment_b(codec: &dyn VenueCodec, symbols: &[String]) -> anyhow::Result<()> {
    if symbols.is_empty() {
        println!("## Experiment B — TCP tuning: no symbols available\n");
        return Ok(());
    }

    let subject: Vec<String> = symbols.iter().take(50).cloned().collect();
    eprintln!("benchmark B: tuned vs default, {} symbols", subject.len());

    let default_cfg = NetConfig {
        tuned: false,
        race_candidates: 1,
        ..NetConfig::default()
    };
    let tuned_cfg = NetConfig {
        tuned: true,
        race_candidates: 1,
        ..NetConfig::default()
    };

    // Both arms run *simultaneously*. Running them one after the other on a
    // non-stationary network measures the network, not the socket options: an
    // earlier sequential run differed 13x in sample count between arms.
    let (default_latencies, tuned_latencies) = tokio::join!(
        sample_feed(codec, &default_cfg, &subject),
        sample_feed(codec, &tuned_cfg, &subject),
    );

    let default_latencies = default_latencies.unwrap_or_else(|error| {
        eprintln!("benchmark B: default arm failed: {error:#}");
        Vec::new()
    });
    let tuned_latencies = tuned_latencies.unwrap_or_else(|error| {
        eprintln!("benchmark B: tuned arm failed: {error:#}");
        Vec::new()
    });

    if default_latencies.is_empty() && tuned_latencies.is_empty() {
        println!("## Experiment B — TCP tuning: no samples (network instability)\n");
        return Ok(());
    }

    println!("## Experiment B — TCP socket tuning");
    println!();
    println!(
        "One-way `received_at - exchange_timestamp` over {} live deltas per \
         configuration ({} symbols).",
        tuned_latencies.len().max(default_latencies.len()),
        subject.len()
    );
    println!();
    println!("| Configuration | samples | p50 | p95 | p99 | p99.9 |");
    println!("| --- | --- | --- | --- | --- | --- |");
    print_latency_row("default OS", &default_latencies);
    print_latency_row("TCP_NODELAY + 2MiB RCVBUF + QUICKACK", &tuned_latencies);
    println!();
    println!(
        "Caveat: the venue timestamp is sometimes absent, in which case the \
         codec falls back to local arrival time and the sample reads as 0 ms. \
         Treat the tail, not the median, as the signal."
    );
    println!();

    Ok(())
}

/// C: how does symbols-per-socket affect time-to-snapshot and delta latency?
async fn experiment_c(codec: &dyn VenueCodec, symbols: &[String]) -> anyhow::Result<()> {
    if symbols.is_empty() {
        println!("## Experiment C — density sweep: no symbols available\n");
        return Ok(());
    }

    let densities = [25usize, 100, 250, 500];
    let config = NetConfig {
        race_candidates: 1,
        ..NetConfig::default()
    };

    println!("## Experiment C — shard density sweep");
    println!();
    println!("| symbols/socket | time to last snapshot | delta p50 | delta p99 | samples |");
    println!("| --- | --- | --- | --- | --- |");

    for density in densities {
        let subject: Vec<String> = symbols.iter().take(density).cloned().collect();
        if subject.is_empty() {
            continue;
        }
        eprintln!(
            "benchmark C: {density} symbols/socket ({} available)",
            subject.len()
        );

        match measure_density_retrying(codec, &config, &subject).await {
            Ok((time_to_last, latencies)) => {
                let mut sorted = latencies.clone();
                sorted.sort_unstable();
                println!(
                    "| {} | {} | {} | {} | {} |",
                    subject.len(),
                    ms(time_to_last),
                    ms(percentile(&sorted, 50, 100)),
                    ms(percentile(&sorted, 99, 100)),
                    sorted.len()
                );
            }
            Err(error) => eprintln!("benchmark C: density {density} failed: {error:#}"),
        }
    }

    println!();
    Ok(())
}

/// D: how much of the path is our own parsing?
fn experiment_d(codec: &dyn VenueCodec) -> anyhow::Result<()> {
    let book = book_frame(50);
    let change = change_frame(5);
    let now = Utc::now();

    // Warm the JSON parser and the allocator.
    for _ in 0..200 {
        let _ = codec.decode_text_frame(&book, now)?;
        let _ = codec.decode_text_frame(&change, now)?;
    }

    let iterations = 20_000u32;
    let book_ns = time_per_call(iterations, || {
        let _ = codec.decode_text_frame(&book, now);
    });
    let change_ns = time_per_call(iterations, || {
        let _ = codec.decode_text_frame(&change, now);
    });

    let prices = 1_000_000u32;
    let mut checksum = 0i64;
    let started = Instant::now();
    for _ in 0..prices {
        checksum = checksum.wrapping_add(parse_scaled_1e6("0.4812").unwrap_or(0));
    }
    std::hint::black_box(checksum);
    let price_ns = started.elapsed().as_secs_f64() * 1e9 / f64::from(prices);

    println!("## Experiment D — parser and runtime overhead");
    println!();
    println!("| Workload | ns/frame | frames/sec |");
    println!("| --- | --- | --- |");
    println!(
        "| `book` frame, 50 levels/side | {book_ns:.0} | {:.0} |",
        1e9 / book_ns.max(f64::EPSILON)
    );
    println!(
        "| `price_change` frame, 5 changes | {change_ns:.0} | {:.0} |",
        1e9 / change_ns.max(f64::EPSILON)
    );
    println!();
    println!(
        "| Workload | ns/call | calls/sec |\n| --- | --- | --- |\n| `parse_scaled_1e6(\"0.4812\")` | {price_ns:.1} | {:.0} |",
        1e9 / price_ns.max(f64::EPSILON)
    );
    println!();

    Ok(())
}

async fn sample_feed(
    codec: &dyn VenueCodec,
    config: &NetConfig,
    symbols: &[String],
) -> anyhow::Result<Vec<Duration>> {
    const ATTEMPTS: u32 = 3;
    let mut last_error = None;

    for attempt in 1..=ATTEMPTS {
        match sample_feed_once(codec, config, symbols).await {
            Ok(latencies) if !latencies.is_empty() => return Ok(latencies),
            Ok(_) => eprintln!("benchmark: feed produced no deltas ({attempt}/{ATTEMPTS})"),
            Err(error) => {
                eprintln!("benchmark: feed attempt failed ({attempt}/{ATTEMPTS}): {error:#}")
            }
        }
        last_error = last_error.or(Some(anyhow::anyhow!("no deltas sampled")));
        time::sleep(Duration::from_secs(1)).await;
    }

    Err(last_error.unwrap_or_else(|| anyhow::anyhow!("no deltas sampled")))
}

async fn sample_feed_once(
    codec: &dyn VenueCodec,
    config: &NetConfig,
    symbols: &[String],
) -> anyhow::Result<Vec<Duration>> {
    let (mut socket, _) = tuned_ws::connect(codec, codec.ws_url(), config).await?;
    subscribe(codec, &mut socket, symbols).await?;
    let (_, latencies) = drain(
        codec,
        &mut socket,
        symbols.len(),
        WARMUP_LIMIT,
        SAMPLE_WINDOW,
    )
    .await?;
    Ok(latencies)
}

async fn measure_density_retrying(
    codec: &dyn VenueCodec,
    config: &NetConfig,
    symbols: &[String],
) -> anyhow::Result<(Duration, Vec<Duration>)> {
    const ATTEMPTS: u32 = 3;
    let mut last_error = None;

    for attempt in 1..=ATTEMPTS {
        match measure_density(codec, config, symbols).await {
            Ok((time_to_last, latencies)) => return Ok((time_to_last, latencies)),
            Err(error) => {
                eprintln!("benchmark C: attempt failed ({attempt}/{ATTEMPTS}): {error:#}");
                last_error = Some(error);
            }
        }
        time::sleep(Duration::from_secs(1)).await;
    }

    Err(last_error.unwrap_or_else(|| anyhow::anyhow!("density measurement failed")))
}

async fn measure_density(
    codec: &dyn VenueCodec,
    config: &NetConfig,
    symbols: &[String],
) -> anyhow::Result<(Duration, Vec<Duration>)> {
    let (mut socket, _) = tuned_ws::connect(codec, codec.ws_url(), config).await?;
    subscribe(codec, &mut socket, symbols).await?;
    // `drain` measures from just after the subscribe frame is sent.
    drain(
        codec,
        &mut socket,
        symbols.len(),
        WARMUP_LIMIT,
        SAMPLE_WINDOW,
    )
    .await
}

async fn subscribe(
    codec: &dyn VenueCodec,
    socket: &mut WsSocket,
    symbols: &[String],
) -> anyhow::Result<()> {
    socket
        .send(Message::Text(
            codec.encode_initial_subscribe(symbols)?.into(),
        ))
        .await?;
    Ok(())
}

/// Reads until every expected symbol has snapshotted (or the warm-up limit),
/// then keeps sampling deltas for `window`.
async fn drain(
    codec: &dyn VenueCodec,
    socket: &mut WsSocket,
    expected: usize,
    warmup: Duration,
    window: Duration,
) -> anyhow::Result<(Duration, Vec<Duration>)> {
    let started = Instant::now();
    let mut seen: HashSet<String> = HashSet::new();
    let mut last_snapshot = started;
    let mut latencies = Vec::new();

    while seen.len() < expected {
        let remaining = warmup.saturating_sub(started.elapsed());
        if remaining.is_zero() {
            break;
        }
        let Some(message) = read_frame(socket, remaining).await? else {
            break;
        };
        for event in decode(codec, &message) {
            match event {
                NormalizedEvent::Snapshot { symbol, .. } => {
                    if seen.insert(symbol) {
                        last_snapshot = Instant::now();
                    }
                }
                NormalizedEvent::Delta {
                    exchange_ts,
                    received_at,
                    ..
                } => push_latency(&mut latencies, received_at, exchange_ts),
                NormalizedEvent::MarketLifecycle { .. } => {}
            }
        }
    }

    let time_to_last = last_snapshot.saturating_duration_since(started);
    let deadline = Instant::now() + window;

    loop {
        let remaining = deadline.saturating_duration_since(Instant::now());
        if remaining.is_zero() {
            break;
        }
        let Some(message) = read_frame(socket, remaining).await? else {
            break;
        };
        for event in decode(codec, &message) {
            if let NormalizedEvent::Delta {
                exchange_ts,
                received_at,
                ..
            } = event
            {
                push_latency(&mut latencies, received_at, exchange_ts);
            }
        }
    }

    Ok((time_to_last, latencies))
}

async fn read_frame(socket: &mut WsSocket, timeout: Duration) -> anyhow::Result<Option<String>> {
    match time::timeout(timeout, socket.next()).await {
        Err(_) => Ok(None),
        Ok(None) => Ok(None),
        Ok(Some(message)) => match message? {
            Message::Text(text) => Ok(Some(text.as_str().to_owned())),
            Message::Ping(payload) => {
                socket.send(Message::Pong(payload)).await?;
                Ok(None)
            }
            Message::Pong(_) | Message::Binary(_) | Message::Frame(_) => Ok(None),
            Message::Close(_) => Ok(None),
        },
    }
}

fn decode(codec: &dyn VenueCodec, raw: &str) -> Vec<NormalizedEvent> {
    codec
        .decode_text_frame(raw, Utc::now())
        .unwrap_or_else(|_| Vec::new())
}

fn push_latency(
    samples: &mut Vec<Duration>,
    received_at: chrono::DateTime<Utc>,
    exchange_ts: chrono::DateTime<Utc>,
) {
    if let Ok(latency) = (received_at - exchange_ts).to_std() {
        samples.push(latency);
    }
}

fn print_latency_row(label: &str, latencies: &[Duration]) {
    let mut sorted = latencies.to_vec();
    sorted.sort_unstable();
    println!(
        "| {label} | {} | {} | {} | {} | {} |",
        sorted.len(),
        ms(percentile(&sorted, 50, 100)),
        ms(percentile(&sorted, 95, 100)),
        ms(percentile(&sorted, 99, 100)),
        ms(percentile(&sorted, 999, 1000))
    );
}

fn time_per_call(iterations: u32, mut call: impl FnMut()) -> f64 {
    let started = Instant::now();
    for _ in 0..iterations {
        call();
    }
    started.elapsed().as_secs_f64() * 1e9 / f64::from(iterations)
}

fn ms(value: Duration) -> String {
    format!("{:.1} ms", value.as_secs_f64() * 1000.0)
}

/// A representative `book` frame with `levels` price levels per side.
fn book_frame(levels: usize) -> String {
    let ladder: Vec<serde_json::Value> = (0..levels)
        .map(|index| {
            serde_json::json!({
                "price": format!("0.{:02}", 40 + index % 20),
                "size": format!("{}.0", 10 + index),
            })
        })
        .collect();

    serde_json::json!({
        "event_type": "book",
        "asset_id": "BENCH",
        "timestamp": "1766789469958",
        "bids": ladder,
        "asks": ladder,
    })
    .to_string()
}

/// A representative `price_change` frame with `changes` level updates.
fn change_frame(changes: usize) -> String {
    let updates: Vec<serde_json::Value> = (0..changes)
        .map(|index| {
            serde_json::json!({
                "asset_id": "BENCH",
                "price": format!("0.{:02}", 40 + index),
                "size": format!("{}.0", 10 + index),
                "side": if index % 2 == 0 { "BUY" } else { "SELL" },
            })
        })
        .collect();

    serde_json::json!({
        "event_type": "price_change",
        "timestamp": "1766789469958",
        "price_changes": updates,
    })
    .to_string()
}
